"""Runs the eval suite and records what it found.

Each case is set up, run `samples` times, and graded by each of its graders.
Results go to `EvalRun` / `EvalResult` so a run can be compared against the
one before it -- which is the entire point, since an absolute score means very
little and a change in score means a great deal.
"""
import logging
import subprocess
import traceback

from django.db import transaction
from django.utils import timezone

from ai_workflows.harness.alerts import suppressed
from ai_workflows.harness.evals.cases import load_cases
from ai_workflows.models import EvalResult, EvalRun

logger = logging.getLogger(__name__)


def _provider_order():
    """The providers and models the suite is about to run against.

    Best-effort: a stubbed-only run does not need a provider at all, and
    failing the run because the catalogue could not answer would make the
    bookkeeping more important than the measurement.
    """
    try:
        from ai_workflows.harness.catalogue import resolve

        return [
            {"provider": name, "model": model_id}
            for name, model_id in resolve(allow_fallback=True)
        ]
    except Exception:  # noqa: BLE001
        logger.exception("[evals] could not record the provider order")
        return []


def _git_sha():
    """Best-effort commit id, so a score can be traced to the code that got it."""
    try:
        return subprocess.check_output(
            ["git", "rev-parse", "HEAD"], text=True, stderr=subprocess.DEVNULL,
        ).strip()[:40]
    except Exception:
        return ""


class EvalRunner:
    """Executes cases against the agents as they currently are.

    Two kinds of case, measuring different things.

    A **stubbed** case pins the model's answer and asks what the *agent* does
    with it: given a reported contradiction, does the gate refuse? Letting the
    live model decide its own answer would make every run measure a different
    question, so this is not a shortcut around measuring the real thing -- it
    is what makes the measurement mean anything.

    A **live** case makes a real call and grades what came back. It is the only
    way to catch the failure that started this whole suite -- the writer
    inventing "a 40% improvement in performance" -- because no stub will invent
    a statistic on the agent's behalf. Live cases cost money, so they are
    opt-in via `live=True`.
    """

    def __init__(self, samples=1, label="", is_baseline=False, stub=None,
                 live=False):
        self.samples = max(1, samples)
        self.label = label
        self.is_baseline = is_baseline
        # Live cases call a real provider, so they cost money and need a key.
        # Off by default: a suite that bills on every run is a suite people
        # stop running, and a suite nobody runs measures nothing.
        self.live = live
        # Injected so tests can supply their own, and so the stub is a
        # dependency of the runner rather than a hidden import.
        self._stub = stub or self._default_stub

    @staticmethod
    def _default_stub(response):
        from editorial.llm_fakes import fake_gemini

        return fake_gemini(response)

    def run(self, agents=None, cases=None):
        registry = load_cases()

        selected = registry.all()
        if agents:
            selected = [c for c in selected if c.agent in agents]
        if cases:
            selected = [c for c in selected if c.name in cases]

        skipped_live = 0
        if not self.live:
            before = len(selected)
            selected = [c for c in selected if not c.is_live]
            skipped_live = before - len(selected)
            if skipped_live:
                logger.info(
                    "[evals] skipping %s live case(s); pass --live to include them",
                    skipped_live,
                )

        if not selected:
            raise ValueError(
                "no eval cases matched the selection"
                + (f" ({skipped_live} live case(s) were skipped; pass --live)"
                   if skipped_live else "")
            )

        run = EvalRun.objects.create(
            label=self.label,
            is_baseline=self.is_baseline,
            agents=sorted({c.agent for c in selected}),
            samples_per_case=self.samples,
            git_sha=_git_sha(),
            provider_order=_provider_order(),
        )

        try:
            # The suite drives the production agents on purpose, so their
            # health must not move because of it. A run that hit a quota limit
            # once marked the real writer as failing and emailed everyone
            # holding `receive_alerts` -- an outage report generated by a test
            # harness, about an agent nobody was using.
            with suppressed(f"eval run #{run.pk}"):
                for case in selected:
                    self._run_case(run, case)
        except Exception as exc:  # noqa: BLE001 - recorded, then re-raised
            run.status = 'failed'
            run.error = f"{exc}\n{traceback.format_exc()}"
            run.finished_at = timezone.now()
            run.save(update_fields=['status', 'error', 'finished_at'])
            raise

        run.status = 'complete'
        run.finished_at = timezone.now()
        run.save(update_fields=['status', 'finished_at'])
        return run

    def _run_case(self, run, case):
        for sample in range(self.samples):
            # Each sample gets its own fixture. Sharing one would let an agent
            # that caches by input -- several of them look up an `existing` row
            # first -- return sample 0's answer for every later sample, and the
            # spread would read as zero.
            with transaction.atomic():
                fixture = case.setup()

            try:
                if case.model_response is not None:
                    with self._stub(case.model_response):
                        output = case.run(fixture)
                else:
                    output = case.run(fixture)
            except Exception as exc:  # noqa: BLE001
                # An agent that raised has not been graded; that is a finding,
                # not a grade of zero.
                logger.exception("[evals] %s raised on sample %s", case.name, sample)
                EvalResult.objects.create(
                    run=run, agent=case.agent, case=case.name, sample=sample,
                    grader='(raised)', score=None, passed=None,
                    detail=f"{type(exc).__name__}: {exc}",
                )
                continue

            # Stored once per sample, before grading, so a later run can be
            # compared against it pairwise. Without this the suite can only
            # ever say "the score changed", never "here is what changed".
            rendered = _render(output)

            for grader in case.graders:
                grade = grader.grade(output, case)
                EvalResult.objects.create(
                    run=run, agent=case.agent, case=case.name, sample=sample,
                    grader=grader.name, score=grade.score, passed=grade.passed,
                    detail=grade.detail,
                    output={**(grade.meta or {}), "rendered": rendered},
                )


def _render(output):
    """The agent's output as text, for storage and later comparison."""
    from ai_workflows.harness.evals.graders import render_for_judging

    try:
        return render_for_judging(output)
    except Exception:  # noqa: BLE001 - never fail a run over bookkeeping
        logger.exception("[evals] could not render an output for storage")
        return ""


def baseline_output(case, run=None):
    """What the baseline run produced for `case`, or "".

    The reference a `PairwiseGrader` compares against. Takes the most recent
    baseline rather than the most recent run: comparing against whatever ran
    last would drift, one small acceptable loss at a time, until the suite was
    measuring against something nobody ever approved.
    """
    from ai_workflows.models import EvalResult, EvalRun

    reference_run = run or EvalRun.objects.filter(
        is_baseline=True, status='complete',
    ).order_by('-started_at').first()
    if reference_run is None:
        return ""

    result = EvalResult.objects.filter(
        run=reference_run, case=case.name,
    ).exclude(output__isnull=True).first()
    if result is None:
        return ""

    return (result.output or {}).get("rendered", "")


def compare(run, baseline):
    """Per-agent score difference between two runs.

    Returns {agent: {"score": x, "baseline": y, "delta": x - y}}, with None
    where either side has no score -- a missing measurement is reported as
    missing rather than silently treated as zero.
    """
    agents = sorted(set(run.agents) | set(baseline.agents))
    out = {}
    for agent in agents:
        now = run.score_for(agent)
        was = baseline.score_for(agent)
        out[agent] = {
            "score": now,
            "baseline": was,
            "delta": None if (now is None or was is None) else now - was,
        }
    return out
